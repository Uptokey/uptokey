export type UiKey = keyof typeof STRINGS

function interpolate(text: string, params?: Record<string, string | number>) {
  if (!params) return text
  return text.replace(/\{(\w+)\}/g, (match, name: string) => (name in params ? String(params[name]) : match))
}

/** Frontend string for the active language; falls through to the shared TUI dictionaries for older keys. */
export function ui(key: UiKey | (string & {}), params?: Record<string, string | number>): string {
  const entry = (STRINGS as Record<string, Entry>)[key]
  if (entry) return interpolate(entry[getLang()], params)
  const row = rowText(key, getLang())
  if (row !== undefined) return interpolate(row, params)
  return t(key, params)
}
